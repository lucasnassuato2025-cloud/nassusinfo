CREATE OR REPLACE FUNCTION public.crm_data_subject_inventory(p_query text DEFAULT '')
RETURNS TABLE(client_id bigint,display_name text,masked_document text,email_hint text,status text,projects_count bigint,payments_count bigint,documents_count bigint,signed_documents_count bigint)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
SELECT c.id,coalesce(nullif(c.trade_name,''),nullif(c.company,''),c.name),
 CASE WHEN length(regexp_replace(coalesce(c.document,''),'\D','','g'))>4 THEN repeat('*',greatest(length(regexp_replace(coalesce(c.document,''),'\D','','g'))-4,0))||right(regexp_replace(coalesce(c.document,''),'\D','','g'),4) ELSE coalesce(c.document,'') END,
 CASE WHEN position('@' in coalesce(c.email,''))>1 THEN left(c.email,1)||'***@'||split_part(c.email,'@',2) ELSE '' END,
 CASE WHEN c.deleted_at IS NULL THEN 'active' ELSE 'trash' END,
 (SELECT count(*) FROM public.projects p WHERE p.client_id=c.id AND p.owner_id=c.owner_id),
 (SELECT count(*) FROM public.payments p WHERE p.client_id=c.id AND p.owner_id=c.owner_id),
 (SELECT count(*) FROM public.commercial_documents d WHERE d.client_id=c.id AND d.owner_id=c.owner_id),
 (SELECT count(*) FROM public.commercial_documents d WHERE d.client_id=c.id AND d.owner_id=c.owner_id AND (d.signature_status='signed' OR d.signed_at IS NOT NULL OR EXISTS(SELECT 1 FROM public.document_signatures s WHERE s.document_id=d.id)))
FROM public.clients c
WHERE c.owner_id=public.crm_workspace_owner_id()::text AND public.crm_can('admin.view')
AND (coalesce(trim(p_query),'')='' OR lower(coalesce(c.name,'')||' '||coalesce(c.trade_name,'')||' '||coalesce(c.company,'')||' '||coalesce(c.email,'')||' '||coalesce(c.document,'')) LIKE '%'||lower(trim(p_query))||'%')
ORDER BY c.updated_at DESC LIMIT 100 $function$;
REVOKE ALL ON FUNCTION public.crm_data_subject_inventory(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_data_subject_inventory(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.crm_export_data_subject(p_client_id bigint) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_owner text:=public.crm_workspace_owner_id()::text; v_result jsonb;
BEGIN
 IF NOT public.crm_can('admin.manage') THEN RAISE EXCEPTION 'Sem permissão para exportar dados do titular.'; END IF;
 SELECT jsonb_build_object('generatedAt',now(),
  'client',(SELECT to_jsonb(c)-'deleted_by'-'deleted_batch' FROM public.clients c WHERE c.id=p_client_id AND c.owner_id=v_owner),
  'projects',coalesce((SELECT jsonb_agg(to_jsonb(p)-'deleted_by'-'deleted_batch') FROM public.projects p WHERE p.client_id=p_client_id AND p.owner_id=v_owner),'[]'::jsonb),
  'payments',coalesce((SELECT jsonb_agg(to_jsonb(p)-'deleted_by'-'deleted_batch') FROM public.payments p WHERE p.client_id=p_client_id AND p.owner_id=v_owner),'[]'::jsonb),
  'documents',coalesce((SELECT jsonb_agg(jsonb_build_object('id',d.id,'number',d.number,'type',d.document_type,'title',d.title,'status',d.status,'issueDate',d.issue_date,'amount',d.amount,'signatureStatus',d.signature_status,'signedAt',d.signed_at,'hash',d.document_hash)) FROM public.commercial_documents d WHERE d.client_id=p_client_id AND d.owner_id=v_owner),'[]'::jsonb)) INTO v_result;
 IF v_result->'client' IS NULL THEN RAISE EXCEPTION 'Titular não encontrado.'; END IF;
 RETURN v_result;
END $function$;
REVOKE ALL ON FUNCTION public.crm_export_data_subject(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_export_data_subject(bigint) TO authenticated;

