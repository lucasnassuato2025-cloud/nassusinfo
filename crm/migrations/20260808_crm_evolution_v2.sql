CREATE OR REPLACE FUNCTION public.crm_apply_role_preset(p_member_id bigint,p_role text) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_permissions jsonb; v_current_role text;
BEGIN
 IF NOT public.crm_can('admin.manage') THEN RAISE EXCEPTION 'Sem permissão.'; END IF;
 SELECT role INTO v_current_role FROM public.crm_team_members WHERE id=p_member_id AND workspace_owner_id=public.crm_workspace_owner_id();
 IF v_current_role IS NULL THEN RAISE EXCEPTION 'Membro não encontrado.'; END IF;
 IF v_current_role='owner' THEN RAISE EXCEPTION 'O papel do proprietário não pode ser alterado por preset.'; END IF;
 IF p_role NOT IN ('admin','commercial','operations','finance','viewer') THEN RAISE EXCEPTION 'Perfil inválido.'; END IF;
 SELECT permissions INTO v_permissions FROM public.crm_role_presets WHERE role=p_role;
 UPDATE public.crm_team_members SET role=p_role,permissions=coalesce(v_permissions,'{}'::jsonb),updated_at=now() WHERE id=p_member_id AND workspace_owner_id=public.crm_workspace_owner_id();
 PERFORM public.crm_record_audit_event('team_role_updated','team_member',p_member_id::text,'warning','success','Perfil de acesso atualizado',jsonb_build_object('role',p_role));
 RETURN true;
END $function$;
