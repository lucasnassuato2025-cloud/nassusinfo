CREATE OR REPLACE FUNCTION public.crm_create_data_subject_request(p_client_id bigint,p_request_type text,p_notes text DEFAULT '') RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_id bigint;
BEGIN
 IF NOT public.crm_can('admin.manage') THEN RAISE EXCEPTION 'Sem permissão para registrar solicitações LGPD.'; END IF;
 IF p_request_type NOT IN ('access','correction','portability','anonymization','deletion','information') THEN RAISE EXCEPTION 'Tipo de solicitação inválido.'; END IF;
 INSERT INTO public.crm_data_subject_requests(workspace_owner_id,client_id,request_type,notes,requested_by)
 VALUES(public.crm_workspace_owner_id(),p_client_id,p_request_type,left(coalesce(p_notes,''),1000),public.crm_auth_user_id()) RETURNING id INTO v_id;
 PERFORM public.crm_record_audit_event('lgpd_request_created','client',p_client_id::text,'info','success','Solicitação de titular registrada',jsonb_build_object('requestId',v_id,'type',p_request_type));
 RETURN v_id;
END $function$;
REVOKE ALL ON FUNCTION public.crm_create_data_subject_request(bigint,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_create_data_subject_request(bigint,text,text) TO authenticated;

