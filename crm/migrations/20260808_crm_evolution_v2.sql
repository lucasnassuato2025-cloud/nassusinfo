CREATE OR REPLACE FUNCTION public.crm_vault_reveal(p_id bigint) RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_owner uuid:=public.crm_workspace_owner_id(); v_key text; v_secret text;
BEGIN
 IF NOT (public.crm_can('infrastructure.write') OR public.crm_can('admin.manage')) THEN RAISE EXCEPTION 'Sem permissão para revelar segredos.'; END IF;
 SELECT key_material INTO v_key FROM public.crm_vault_master WHERE workspace_owner_id=v_owner;
 SELECT pgp_sym_decrypt(v.secret_cipher,v_key) INTO v_secret FROM public.crm_vault_items v WHERE v.id=p_id AND v.workspace_owner_id=v_owner;
 IF v_secret IS NULL THEN RAISE EXCEPTION 'Item do cofre não encontrado.'; END IF;
 UPDATE public.crm_vault_items SET last_revealed_at=now() WHERE id=p_id AND workspace_owner_id=v_owner;
 PERFORM public.crm_record_audit_event('vault_item_revealed','vault_item',p_id::text,'warning','success','Segredo do cofre revelado por usuário autorizado','{}'::jsonb);
 RETURN v_secret;
END $function$;
REVOKE ALL ON FUNCTION public.crm_vault_reveal(bigint) FROM PUBLIC;
