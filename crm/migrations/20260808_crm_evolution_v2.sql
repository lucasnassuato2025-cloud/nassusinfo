CREATE OR REPLACE FUNCTION public.crm_auth_security_summary() RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public','auth','neon_auth','pg_temp' AS $function$
DECLARE v_user uuid:=public.crm_auth_user_id();
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Sessão inválida.'; END IF;
 RETURN jsonb_build_object('emailVerified',coalesce((SELECT u."emailVerified" FROM neon_auth."user" u WHERE u.id=v_user),false),'activeSessions',(SELECT count(*) FROM neon_auth.session s WHERE s."userId"=v_user AND s."expiresAt">now()),'lastSessionAt',(SELECT max(s."createdAt") FROM neon_auth.session s WHERE s."userId"=v_user),'passwordAccount',EXISTS(SELECT 1 FROM neon_auth.account a WHERE a."userId"=v_user AND a."providerId"='credential'),'generatedAt',now());
END $function$;
