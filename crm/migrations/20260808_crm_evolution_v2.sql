-- AUDITORIA CENTRAL
CREATE TABLE IF NOT EXISTS public.crm_audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_owner_id uuid NOT NULL,
  actor_user_id uuid,
  event_type text NOT NULL,
  entity_type text NOT NULL DEFAULT '',
  entity_id text NOT NULL DEFAULT '',
  severity text NOT NULL DEFAULT 'info',
  outcome text NOT NULL DEFAULT 'success',
  message text NOT NULL DEFAULT '',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS crm_audit_events_workspace_created_idx ON public.crm_audit_events(workspace_owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS crm_audit_events_event_created_idx ON public.crm_audit_events(workspace_owner_id, event_type, created_at DESC);
REVOKE ALL ON public.crm_audit_events FROM PUBLIC, anonymous, authenticated;

CREATE OR REPLACE FUNCTION public.crm_record_audit_event(
  p_event_type text, p_entity_type text DEFAULT '', p_entity_id text DEFAULT '',
  p_severity text DEFAULT 'info', p_outcome text DEFAULT 'success',
  p_message text DEFAULT '', p_metadata jsonb DEFAULT '{}'::jsonb
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_id bigint; v_owner uuid:=public.crm_workspace_owner_id();
BEGIN
  IF v_owner IS NULL OR public.crm_auth_user_id() IS NULL THEN RAISE EXCEPTION 'Sessão inválida.'; END IF;
  INSERT INTO public.crm_audit_events(workspace_owner_id,actor_user_id,event_type,entity_type,entity_id,severity,outcome,message,metadata)
  VALUES(v_owner,public.crm_auth_user_id(),left(coalesce(p_event_type,''),80),left(coalesce(p_entity_type,''),60),left(coalesce(p_entity_id,''),120),
    CASE WHEN p_severity IN ('info','warning','error','critical') THEN p_severity ELSE 'info' END,
    CASE WHEN p_outcome IN ('success','denied','failed') THEN p_outcome ELSE 'success' END,
    left(coalesce(p_message,''),500),coalesce(p_metadata,'{}'::jsonb)-ARRAY['password','token','access_code','cpf','cnpj','document','secret'])
  RETURNING id INTO v_id;
  RETURN v_id;
END $function$;
REVOKE ALL ON FUNCTION public.crm_record_audit_event(text,text,text,text,text,text,jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_record_audit_event(text,text,text,text,text,text,jsonb) TO authenticated;

CREATE OR REPLACE FUNCTION public.crm_list_audit_events(p_limit integer DEFAULT 200)
RETURNS TABLE(id bigint,event_type text,entity_type text,entity_id text,severity text,outcome text,message text,metadata jsonb,actor_name text,created_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
SELECT e.id,e.event_type,e.entity_type,e.entity_id,e.severity,e.outcome,e.message,e.metadata,
       coalesce(m.name,m.email,'Sistema'),e.created_at
FROM public.crm_audit_events e
LEFT JOIN public.crm_team_members m ON m.user_id=e.actor_user_id AND m.workspace_owner_id=e.workspace_owner_id
WHERE e.workspace_owner_id=public.crm_workspace_owner_id() AND public.crm_can('admin.view')
ORDER BY e.created_at DESC LIMIT greatest(1,least(coalesce(p_limit,200),500)) $function$;
REVOKE ALL ON FUNCTION public.crm_list_audit_events(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_list_audit_events(integer) TO authenticated;

-- RETENÇÃO POR TIPO DE DADO
CREATE TABLE IF NOT EXISTS public.crm_retention_policies (
  workspace_owner_id uuid NOT NULL,
  record_type text NOT NULL,
  retention_days integer NOT NULL CHECK (retention_days BETWEEN 1 AND 3650),
  preserve_signed boolean NOT NULL DEFAULT false,
  legal_basis text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(workspace_owner_id,record_type)
);
REVOKE ALL ON public.crm_retention_policies FROM PUBLIC, anonymous, authenticated;
INSERT INTO public.crm_retention_policies(workspace_owner_id,record_type,retention_days,preserve_signed,legal_basis)
SELECT workspace_owner_id,x.record_type,x.days,x.preserve,x.basis
FROM public.crm_settings CROSS JOIN (VALUES
 ('clients',90,false,'Gestão comercial e direitos do titular'),
 ('projects',90,false,'Execução de serviços'),
 ('payments',365,true,'Comprovação financeira e exercício regular de direitos'),
 ('commercial_documents',365,true,'Execução contratual e exercício regular de direitos'),
 ('tasks',30,false,'Operação interna'),('site_audits',90,false,'Prestação de serviço'),
 ('site_infrastructure',90,false,'Operação técnica'),('access_credentials',30,false,'Segurança e minimização'),
 ('renewal_costs',365,false,'Gestão financeira')) AS x(record_type,days,preserve,basis)
ON CONFLICT(workspace_owner_id,record_type) DO NOTHING;

CREATE OR REPLACE FUNCTION public.crm_list_retention_policies()
RETURNS TABLE(record_type text,retention_days integer,preserve_signed boolean,legal_basis text,updated_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
SELECT p.record_type,p.retention_days,p.preserve_signed,p.legal_basis,p.updated_at
FROM public.crm_retention_policies p WHERE p.workspace_owner_id=public.crm_workspace_owner_id() AND public.crm_can('admin.view') ORDER BY p.record_type $function$;
REVOKE ALL ON FUNCTION public.crm_list_retention_policies() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_list_retention_policies() TO authenticated;

CREATE OR REPLACE FUNCTION public.crm_update_retention_policy(p_record_type text,p_days integer,p_preserve_signed boolean,p_legal_basis text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
BEGIN
 IF NOT public.crm_can('admin.manage') THEN RAISE EXCEPTION 'Sem permissão para alterar retenção.'; END IF;
 IF p_days<1 OR p_days>3650 THEN RAISE EXCEPTION 'Prazo de retenção inválido.'; END IF;
 INSERT INTO public.crm_retention_policies(workspace_owner_id,record_type,retention_days,preserve_signed,legal_basis,updated_at)
 VALUES(public.crm_workspace_owner_id(),left(p_record_type,80),p_days,p_preserve_signed,left(coalesce(p_legal_basis,''),500),now())
 ON CONFLICT(workspace_owner_id,record_type) DO UPDATE SET retention_days=excluded.retention_days,preserve_signed=excluded.preserve_signed,legal_basis=excluded.legal_basis,updated_at=now();
 PERFORM public.crm_record_audit_event('retention_policy_updated','retention_policy',p_record_type,'warning','success','Política de retenção atualizada',jsonb_build_object('days',p_days,'preserveSigned',p_preserve_signed));
 RETURN true;
END $function$;
REVOKE ALL ON FUNCTION public.crm_update_retention_policy(text,integer,boolean,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_update_retention_policy(text,integer,boolean,text) TO authenticated;

-- LIXEIRA V2
CREATE INDEX IF NOT EXISTS commercial_documents_deleted_batch_idx ON public.commercial_documents(deleted_batch) WHERE deleted_at IS NOT NULL;
CREATE OR REPLACE FUNCTION public.crm_list_trash_v2()
RETURNS TABLE(batch_id uuid,table_name text,record_id bigint,record_type text,label text,deleted_at timestamptz,deleted_reason text,purge_at timestamptz,deleted_by uuid,deleted_by_name text,protected_evidence boolean)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
WITH items(batch_id,table_name,record_id,record_type,label,deleted_at,deleted_reason,deleted_by,protected_evidence,retention_type) AS (
 SELECT deleted_batch,'clients',id,'Cliente',coalesce(nullif(trade_name,''),nullif(company,''),name),deleted_at,deleted_reason,deleted_by,false,'clients' FROM public.clients WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'projects',id,'Projeto',name,deleted_at,deleted_reason,deleted_by,false,'projects' FROM public.projects WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'payments',id,'Cobrança',description,deleted_at,deleted_reason,deleted_by,false,'payments' FROM public.payments WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT d.deleted_batch,'commercial_documents',d.id,CASE d.document_type WHEN 'contrato' THEN 'Contrato' WHEN 'recibo' THEN 'Comprovante' ELSE 'Proposta' END,d.number||' · '||d.title,d.deleted_at,d.deleted_reason,d.deleted_by,(d.signature_status='signed' OR d.signed_at IS NOT NULL OR EXISTS(SELECT 1 FROM public.document_signatures s WHERE s.document_id=d.id)),'commercial_documents' FROM public.commercial_documents d WHERE d.owner_id=public.crm_workspace_owner_id()::text AND d.deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'tasks',id,'Tarefa',title,deleted_at,deleted_reason,deleted_by,false,'tasks' FROM public.tasks WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'site_infrastructure',id,'Infraestrutura',coalesce(nullif(site_name,''),nullif(primary_domain,''),'Site'),deleted_at,deleted_reason,deleted_by,false,'site_infrastructure' FROM public.site_infrastructure WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'access_credentials',id,'Acesso',coalesce(nullif(platform,''),nullif(category,''),'Credencial'),deleted_at,deleted_reason,deleted_by,false,'access_credentials' FROM public.access_credentials WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'renewal_costs',id,'Renovação',coalesce(nullif(plan_domain,''),nullif(provider,''),nullif(item_type,''),'Custo'),deleted_at,deleted_reason,deleted_by,false,'renewal_costs' FROM public.renewal_costs WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
 UNION ALL SELECT deleted_batch,'site_audits',id,'Auditoria',coalesce(nullif(title,''),url),deleted_at,deleted_reason,deleted_by,false,'site_audits' FROM public.site_audits WHERE owner_id=public.crm_workspace_owner_id()::text AND deleted_at IS NOT NULL
)
SELECT i.batch_id,i.table_name,i.record_id,i.record_type,i.label,i.deleted_at,i.deleted_reason,
       i.deleted_at+make_interval(days=>coalesce(p.retention_days,s.trash_retention_days,30)),i.deleted_by,
       coalesce(tm.name,tm.email,'Usuário do CRM'),i.protected_evidence
FROM items i
LEFT JOIN public.crm_retention_policies p ON p.workspace_owner_id=public.crm_workspace_owner_id() AND p.record_type=i.retention_type
LEFT JOIN public.crm_settings s ON s.workspace_owner_id=public.crm_workspace_owner_id()
LEFT JOIN public.crm_team_members tm ON tm.user_id=i.deleted_by AND tm.workspace_owner_id=public.crm_workspace_owner_id()
WHERE public.crm_can('admin.view') ORDER BY i.deleted_at DESC,i.batch_id,i.table_name $function$;
REVOKE ALL ON FUNCTION public.crm_list_trash_v2() FROM PUBLIC, anonymous;
GRANT EXECUTE ON FUNCTION public.crm_list_trash_v2() TO authenticated;

CREATE OR REPLACE FUNCTION public.crm_purge_expired_trash() RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_batch uuid; v_total integer:=0;
BEGIN
 IF NOT public.crm_can('admin.manage') THEN RETURN 0; END IF;
 FOR v_batch IN SELECT DISTINCT t.batch_id FROM public.crm_list_trash_v2() t WHERE t.batch_id IS NOT NULL AND t.purge_at<=now() AND NOT t.protected_evidence
 LOOP v_total:=v_total+public.crm_purge_trash_batch(v_batch); END LOOP;
 RETURN v_total;
END $function$;

