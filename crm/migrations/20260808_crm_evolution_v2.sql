CREATE OR REPLACE FUNCTION public.crm_vault_put(p_id bigint,p_client_id bigint,p_project_id bigint,p_label text,p_username_hint text,p_secret text,p_notes text DEFAULT '') RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','auth','pg_temp' AS $function$
DECLARE v_owner uuid:=public.crm_workspace_owner_id(); v_key text; v_id bigint;
BEGIN
 IF NOT (public.crm_can('infrastructure.write') OR public.crm_can('admin.manage')) THEN RAISE EXCEPTION 'Sem permissão para usar o cofre.'; END IF;
 IF length(coalesce(p_secret,''))<1 OR length(p_secret)>4096 THEN RAISE EXCEPTION 'Segredo inválido.'; END IF;
 INSERT INTO public.crm_vault_master(workspace_owner_id,key_material) VALUES(v_owner,encode(gen_random_bytes(32),'hex')) ON CONFLICT(workspace_owner_id) DO NOTHING;
 SELECT key_material INTO v_key FROM public.crm_vault_master WHERE workspace_owner_id=v_owner;
 IF p_id IS NULL THEN
  INSERT INTO public.crm_vault_items(workspace_owner_id,client_id,project_id,label,username_hint,secret_cipher,notes,created_by)
  VALUES(v_owner,p_client_id,p_project_id,left(trim(p_label),120),left(coalesce(p_username_hint,''),200),pgp_sym_encrypt(p_secret,v_key,'cipher-algo=aes256'),left(coalesce(p_notes,''),1000),public.crm_auth_user_id()) RETURNING id INTO v_id;
 ELSE
  UPDATE public.crm_vault_items SET client_id=p_client_id,project_id=p_project_id,label=left(trim(p_label),120),username_hint=left(coalesce(p_username_hint,''),200),secret_cipher=pgp_sym_encrypt(p_secret,v_key,'cipher-algo=aes256'),notes=left(coalesce(p_notes,''),1000),updated_at=now()
  WHERE id=p_id AND workspace_owner_id=v_owner RETURNING id INTO v_id;
 END IF;
 IF v_id IS NULL THEN RAISE EXCEPTION 'Item do cofre não encontrado.'; END IF;
 PERFORM public.crm_record_audit_event('vault_item_saved','vault_item',v_id::text,'warning','success','Item protegido salvo no cofre',jsonb_build_object('label',left(trim(p_label),120)));
 RETURN v_id;
END $function$;
REVOKE ALL ON FUNCTION public.crm_vault_put(bigint,bigint,bigint,text,text,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_vault_put(bigint,bigint,bigint,text,text,text,text) TO authenticated;

